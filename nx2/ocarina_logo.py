"""(ocarina) The Ocarina Engine icon (blue ocarina) as a C header in the Vulkan back end: gpu/vk/ocarina_logo.h, straight RGBA
bytes, drawn by the Insert menu's banner and the start-up screen (vk_imgui.cpp brand_logo). Kept in the repository, so a
hookshot_vk.dll built anywhere carries it (players replace that DLL alone).

    python nx2/ocarina_logo.py <icone-256.png> [gpu/vk/ocarina_logo.h] [size]

The picture is shrunk to size x size (128 by default: the banner draws it at about 40 points) by box averaging with
premultiplied alpha (no dark fringe on the transparent edge). Standard library only (nx2/logo_rgba.py decodes the PNG).
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import logo_rgba  # noqa: E402

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
OUT = os.path.join(ROOT, "gpu", "vk", "ocarina_logo.h")


def shrink(w, h, px, size):
    """RGBA bytes of w x h shrunk to size x size (each output pixel the premultiplied mean of its source box)"""
    out = bytearray(size * size * 4)
    for oy in range(size):
        y0, y1 = oy * h // size, max(oy * h // size + 1, (oy + 1) * h // size)
        for ox in range(size):
            x0, x1 = ox * w // size, max(ox * w // size + 1, (ox + 1) * w // size)
            r = g = b = a = n = 0
            for y in range(y0, y1):
                row = y * w * 4
                for x in range(x0, x1):
                    i = row + x * 4
                    al = px[i + 3]
                    r += px[i] * al
                    g += px[i + 1] * al
                    b += px[i + 2] * al
                    a += al
                    n += 1
            o = (oy * size + ox) * 4
            if a:
                out[o], out[o + 1], out[o + 2] = (min(255, (r + a // 2) // a), min(255, (g + a // 2) // a),
                                                  min(255, (b + a // 2) // a))
            out[o + 3] = (a + n // 2) // n
    return bytes(out)


def header(png_path, size):
    w, h, px = logo_rgba.decode(open(png_path, "rb").read())
    if size and (w, h) != (size, size):
        px, w, h = shrink(w, h, px, size), size, size
    lines = ["// generated by nx2/ocarina_logo.py from the Ocarina Engine icon (icone-256.png): do not edit",
             "#pragma once",
             "#define OCARINA_LOGO 1",
             "static const unsigned ocarina_logo_w = %d, ocarina_logo_h = %d;" % (w, h),
             "static const unsigned char ocarina_logo_rgba[%d] = {" % len(px)]
    for i in range(0, len(px), 32):
        lines.append(",".join(str(b) for b in px[i:i + 32]) + ",")
    lines.append("};")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    out = sys.argv[2] if len(sys.argv) > 2 else OUT
    size = int(sys.argv[3]) if len(sys.argv) > 3 else 128
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(header(sys.argv[1], size))
    print("ocarina_logo: %s" % out)
